const raw = JSON.parse(readFileSync(MAIN, 'utf8'))
const data = raw.data
const now = Date.now()

const idByName = new Map()
data.ingredients.forEach(i => idByName.set(i.name, i.id))

// ---------- ① 拆分「或」式食材 ----------
const pairPairs = [] // 供生成替代关系用
let splitCount = 0

for (const dish of data.dishes) {
  for (const ing of dish.ingredients || []) {
    const name = String(ing.name || '').trim()
    // 已拆过的直接收集配对，保证脚本可重复执行
    if (Array.isArray(ing.alternatives) && ing.alternatives.length) {
      pairPairs.push([ing.name, ...ing.alternatives])
      continue
    }
    if (!name.includes('或')) continue
    const parts = name.split('或').map(s => s.trim()).filter(Boolean)
    if (parts.length < 2) continue
    ing.name = parts[0]
    ing.alternatives = parts.slice(1)
    splitCount++
    pairPairs.push(parts)
    dish.updatedAt = now
  }
}

// ---------- ② 生成替代食材 ----------
// 先收集：人工表 + 菜谱「或」式配对（双向，只收库里存在的）
const map = new Map() // name -> [{ name, note }]
const add = (from, to, note) => {
  if (!from || !to || from === to) return
  if (!idByName.has(from) || !idByName.has(to)) return
  if (!map.has(from)) map.set(from, [])
  const list = map.get(from)
  if (list.some(x => x.name === to)) return
  list.push({ name: to, note })
}

for (const [from, list] of Object.entries(SUBSTITUTES)) {
  for (const [to, note] of list) add(from, to, note)
}

// 菜谱里的「A或B」是最可靠的互替关系（双向）
for (const parts of pairPairs) {
  for (let i = 0; i < parts.length; i++) {
    for (let j = 0; j < parts.length; j++) {
      if (i === j) continue
      add(parts[i], parts[j], '菜谱中常见互换')
    }
  }
}

let withSubs = 0
const MAX_SUBS = 4
const emojiByName = new Map()
data.ingredients.forEach(i => emojiByName.set(i.name, i.emoji || ''))
for (const ing of data.ingredients) {
  const list = map.get(ing.name)
  if (!list || !list.length) {
    delete ing.substitutes
    continue
  }
  // 带上 id / emoji，前端可直接跳转，不用再查表
  ing.substitutes = list.slice(0, MAX_SUBS).map(s => ({
    name: s.name,
    id: idByName.get(s.name),
    emoji: emojiByName.get(s.name) || '',
    note: s.note,
  }))
  withSubs++
}

// ---------- ③ 写回 + 版本号 ----------
